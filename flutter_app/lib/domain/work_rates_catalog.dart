/// One priced work item inside a category.
class WorkRateItem {
  WorkRateItem({
    required this.matchKey,
    required this.name,
    required this.unit,
    this.unitPrice = 0,
  });

  String matchKey;
  String name;
  String unit;
  double unitPrice;

  Map<String, dynamic> toJson() => {
        'match_key': matchKey,
        'name': name,
        'unit': unit,
        'unit_price': unitPrice,
      };

  static WorkRateItem fromJson(Map<String, dynamic> json) => WorkRateItem(
        matchKey: json['match_key'] as String? ?? '',
        name: json['name'] as String? ?? '',
        unit: json['unit'] as String? ?? 'м²',
        unitPrice: (json['unit_price'] as num?)?.toDouble() ?? 0,
      );
}

class WorkRateCategory {
  WorkRateCategory({
    required this.id,
    required this.name,
    List<WorkRateItem>? items,
  }) : items = items ?? [];

  String id;
  String name;
  List<WorkRateItem> items;

  Map<String, dynamic> toJson() => {
        'id': id,
        'name': name,
        'items': items.map((e) => e.toJson()).toList(),
      };

  static WorkRateCategory fromJson(Map<String, dynamic> json) => WorkRateCategory(
        id: json['id'] as String? ?? '',
        name: json['name'] as String? ?? '',
        items: (json['items'] as List<dynamic>? ?? [])
            .map((e) => WorkRateItem.fromJson(Map<String, dynamic>.from(e as Map)))
            .toList(),
      );
}

WorkRateItem _i(String key, String name, String unit, double price) =>
    WorkRateItem(matchKey: key, name: name, unit: unit, unitPrice: price);

