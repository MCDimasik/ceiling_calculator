/// Plain-language explanation of material quantities (for the materials screen).
String materialsFormulasText({
  required String ceilingLabel,
  required double areaM2,
  required double perimeterM,
}) {
  final calcType = switch (ceilingLabel) {
    'GL' => 'grilyato_gl',
    'Грильято' => 'grilyato_classic',
    _ => 'armstrong',
  };

  final area = areaM2.toStringAsFixed(2);
  final peri = perimeterM.toStringAsFixed(2);

  final lines = <String>[
    'Как считаются материалы',
    '',
    'Размеры комнаты',
    '• Периметр: $peri м',
    '• Площадь: $area м²',
    '',
    'Уголок по периметру',
    'Длину периметра делим на 3 м (длина одной штуки) и округляем вверх.',
    '',
  ];

  if (calcType == 'armstrong' || calcType == 'grilyato_gl') {
    lines.addAll([
      'Каркас (направляющие и подвесы)',
      'Количество всегда берётся с раскладки: с вашего чертежа или, '
          'если линий нет, с автоматического каркаса (несущие 3600). '
          'Учитываются подрезка и стыковка обрезков.',
      '• Подвесы: количество несущих 3600 × 4',
    ]);
  } else {
    lines.addAll([
      'Каркас (направляющие и подвесы)',
      'Количество всегда берётся с раскладки: с вашего чертежа или, '
          'если линий нет, с автоматического каркаса (несущие 2400, '
          'как у Армстронга). Учитываются подрезка и стыковка обрезков.',
      '• Соединители: столько же, сколько несущих 2400',
      '• Подвесы: количество несущих 2400 × 3',
    ]);
  }

  if (calcType == 'grilyato_gl' || calcType == 'grilyato_classic') {
    lines.addAll([
      '',
      'Кассеты (сколько покупать)',
      'Берём большее из двух:',
      '• по площади — как считают поставщики (на комнату 10×10 м → 278 шт.)',
      '• по раскладке — целые кассеты + обрезки: площадь всех резов делим '
          'на 0,36 м² и округляем вверх; куски короче 3 см не считаем',
      '',
      'Решётка «папа» и «мама» (профили по 600 мм)',
      'На каждую купленную кассету:',
      '• ячейка 50×50 → по 11 шт. папа и 11 шт. мама',
      '• ячейка 75×75 → по 7 шт.',
      '• ячейка 100×100 → по 5 шт.',
    ]);
    if (calcType == 'grilyato_gl') {
      lines.add('• L-профиль / заглушки: 4 шт. на каждую кассету');
    }
  } else {
    lines.addAll([
      '',
      'Плиты Армстронг (сколько покупать)',
      'Берём большее из двух: расчёт по площади (площадь ÷ 0,36 м², '
          'округление вверх) или упаковка по фактической раскладке на чертеже. '
          'На экране раскладки по-прежнему видны целые и резаные ячейки.',
    ]);
  }

  lines.addAll([
    '',
    'Светильники',
    '• Армстронг: на каждый светильник минус 1 плита',
    '• Грильято: на каждый светильник минус столько профилей папа/мама, '
        'сколько приходится на одну кассету '
        '(ячейка 50×50 → 11, 75×75 → 7, 100×100 → 5)',
  ]);

  return lines.join('\n');
}
